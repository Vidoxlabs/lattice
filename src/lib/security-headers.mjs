// One definition of the response headers, used twice: `scripts/postbuild.mjs`
// writes them into `dist/client/_headers` for the static assets, and the
// generated Worker entry applies them to every response it returns, including
// the dynamic API routes and the canonical-host redirect. Keeping one module
// means the two paths cannot drift.

const CANONICAL_PRODUCTION_HOST = 'vidoxlabs.com';

/**
 * The policy grants no `unsafe-inline` and no `unsafe-eval`, so every script is
 * a same-origin file, every stylesheet is a same-origin file and no inline
 * style attribute is allowed. The one exception is a hash-listed `<style>`
 * block that a synced web component builds in its shadow root; the build
 * computes that hash from the shipped file, so no source is trusted implicitly.
 * Pages are asserted against the policy by a browser test that fails on any
 * violation.
 *
 * @param {string[]} styleHashes quoted `sha256-` sources
 * @returns {string}
 */
export function contentSecurityPolicy(styleHashes = []) {
  return [
    "default-src 'self'",
    "script-src 'self'",
    ['style-src', "'self'", ...styleHashes].join(' '),
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "object-src 'none'"
  ].join('; ');
}

/**
 * Headers that apply on every host and every response.
 * @param {string[]} styleHashes quoted `sha256-` sources for hash-listed blocks
 * @returns {[string, string][]}
 */
export function securityHeaders(styleHashes = []) {
  return [
    ['Content-Security-Policy', contentSecurityPolicy(styleHashes)],
    ['Referrer-Policy', 'strict-origin-when-cross-origin'],
    ['X-Content-Type-Options', 'nosniff'],
    ['X-Frame-Options', 'DENY'],
    ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=()'],
    ['Cross-Origin-Opener-Policy', 'same-origin']
  ];
}

/**
 * Transport security is pinned only where the site is canonical and served over
 * the production domain. A preview host or a local run must not pin a scheme.
 *
 * The policy covers this host alone: `includeSubDomains` would also pin every
 * subdomain of the canonical domain, including ones this site does not serve,
 * and `preload` would make that permanent in browsers. Both stay out until
 * every subdomain is HTTPS by decision rather than by hope.
 * @type {[string, string]}
 */
export const HSTS_HEADER = ['Strict-Transport-Security', 'max-age=31536000'];

/**
 * Every header for a response on the given host.
 * @param {string} hostname the request hostname
 * @param {string[]} styleHashes quoted `sha256-` sources for hash-listed blocks
 * @returns {[string, string][]}
 */
export function headersForHost(hostname, styleHashes = []) {
  const headers = securityHeaders(styleHashes);
  return hostname === CANONICAL_PRODUCTION_HOST ? [...headers, HSTS_HEADER] : headers;
}

/**
 * The `_headers` file body for the built static assets. Host-conditional headers
 * are omitted because an asset rule cannot see the request host; the Worker
 * entry applies those.
 * @param {string[]} styleHashes quoted `sha256-` sources for hash-listed blocks
 * @returns {string}
 */
export function headersFileBody(styleHashes = []) {
  const block = securityHeaders(styleHashes).map(([name, value]) => `  ${name}: ${value}`).join('\n');
  return `# Generated by scripts/postbuild.mjs from src/lib/security-headers.mjs.\n/*\n${block}\n`;
}
