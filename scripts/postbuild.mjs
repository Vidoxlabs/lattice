import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { sanitizeWorkerBundle } from './bundle-hygiene.mjs';
import { headersFileBody } from '../src/lib/security-headers.mjs';
import { collectStyleHashes } from '../src/lib/csp-hashes.mjs';
import { builtRoutes, robotsTxt, sitemapXml } from '../src/lib/discoverability.mjs';
import { siteOrigin } from '../src/lib/site.mjs';

// The Cloudflare build emits one of two deploy configurations:
// - a full Worker deploy (dist/server/wrangler.json, main entry) when at least
//   one route opts out of prerendering, or
// - an assets-only deploy (dist/client/wrangler.json) when every route is
//   prerendered and no Worker script exists.
// In both cases the generated config must not carry the private workstation
// paths the generator embeds, and the Worker deploy must route every request
// through the canonical-host check before the framework handler, because the
// framework serves matched static assets without running page middleware.

const serverConfigPath = 'dist/server/wrangler.json';
const clientConfigPath = 'dist/client/wrangler.json';

if (existsSync(serverConfigPath)) {
  copyFileSync('src/lib/host.mjs', 'dist/server/host.mjs');
  copyFileSync('src/lib/security-headers.mjs', 'dist/server/security-headers.mjs');
  // A synced web component builds a `<style>` block in its shadow root, which a
  // strict policy blocks unless the block is hash-listed. The hash comes from
  // the file the build ships, never from a hand-written list.
  const styleHashes = collectStyleHashes('dist/client');
  writeFileSync('dist/server/csp-hashes.mjs', `export const STYLE_HASHES = ${JSON.stringify(styleHashes)};\n`);
  writeFileSync('dist/server/host-entry.mjs', [
    "import server from './entry.mjs';",
    "import { canonicalRedirect } from './host.mjs';",
    "import { headersForHost } from './security-headers.mjs';",
    "import { STYLE_HASHES } from './csp-hashes.mjs';",
    '',
    '// Generated by scripts/postbuild.mjs. The framework handler serves matched',
    '// static assets before page middleware runs, so the canonical-host rule is',
    '// checked ahead of it for every request that reaches the Worker.',
    '',
    '/**',
    ' * Apply the security headers to every response, including API routes, streamed',
    ' * chat answers and the redirect. Transport security is host-conditional, so the',
    ' * request host decides whether it is added.',
    ' */',
    'function withSecurityHeaders(request, response) {',
    '  const headers = new Headers(response.headers);',
    '  for (const [name, value] of headersForHost(new URL(request.url).hostname, STYLE_HASHES)) headers.set(name, value);',
    '  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });',
    '}',
    '',
    'export default {',
    '  async fetch(request, env, context) {',
    '    const destination = canonicalRedirect(request.url);',
    '    if (destination) return withSecurityHeaders(request, Response.redirect(destination, 301));',
    '    return withSecurityHeaders(request, await server.fetch(request, env, context));',
    '  }',
    '}',
    ''
  ].join('\n'));

  const config = JSON.parse(readFileSync(serverConfigPath, 'utf8'));
  delete config.configPath;
  delete config.userConfigPath;
  delete config.dev;
  config.main = 'host-entry.mjs';
  // Every request reaches the Worker so the canonical-host rule runs before the
  // framework serves a matched static asset. Host-scoped pattern entries are
  // not part of the supported route syntax, so the boolean is the only form
  // that keeps the redirect working on static pages.
  config.assets.run_worker_first = true;
  writeFileSync(serverConfigPath, `${JSON.stringify(config)}\n`);

  // The framework bundle embeds the absolute project path. It is inert at
  // runtime but must not leave the build machine, and a checkout can live under
  // any root in a folder with any name, so the path comes from the working
  // directory rather than from a pattern; the build fails if an occurrence
  // survives.
  const rewritten = sanitizeWorkerBundle({ directory: 'dist/server', projectRoot: process.cwd() });
  console.log(`Prepared the Worker deploy configuration with the host entry (${rewritten.length} modules sanitized).`);
} else {
  if (!existsSync(clientConfigPath)) throw new Error('No deploy configuration was generated by the build.');
  const config = JSON.parse(readFileSync(clientConfigPath, 'utf8'));
  delete config.configPath;
  delete config.userConfigPath;
  delete config.dev;
  writeFileSync(clientConfigPath, `${JSON.stringify(config)}\n`);
  console.log('Prepared the assets-only deploy configuration. Add a non-prerendered route to ship a Worker.');
}

// The static assets get the same headers through the `_headers` file the asset
// server reads. The framework has already written its immutable cache rule
// there, so the generated security block is prepended and the rest is kept.
const headersPath = 'dist/client/_headers';
const existingHeaders = existsSync(headersPath) ? readFileSync(headersPath, 'utf8').trimStart() : '';
writeFileSync(headersPath, `${headersFileBody(collectStyleHashes('dist/client'))}${existingHeaders ? `\n${existingHeaders}` : ''}`);
console.log('Wrote dist/client/_headers from the shared header definition.');

// The sitemap and robots file are derived from the routes the build published,
// so a documentation sync arrives in both without anyone editing a list.
const origin = siteOrigin();
const routes = builtRoutes('dist/client');
writeFileSync('dist/client/sitemap.xml', sitemapXml(routes, origin));
writeFileSync('dist/client/robots.txt', robotsTxt(origin));
console.log(`Wrote the sitemap and robots file for ${routes.length} routes on ${origin}.`);
