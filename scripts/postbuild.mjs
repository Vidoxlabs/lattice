import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

// The Cloudflare build emits one of two deploy configurations:
// - a full Worker deploy (dist/server/wrangler.json, main entry) when at least
//   one route opts out of prerendering, or
// - an assets-only deploy (dist/client/wrangler.json) when every route is
//   prerendered and no Worker script exists.
// In both cases the generated config must not carry the private workstation
// paths the generator embeds, and the Worker deploy must route every request
// through the canonical-host check before the framework handler, because the
// framework serves matched static assets without running page middleware.

const serverConfigPath = 'dist/server/wrangler.json';
const clientConfigPath = 'dist/client/wrangler.json';

if (existsSync(serverConfigPath)) {
  copyFileSync('src/lib/host.mjs', 'dist/server/host.mjs');
  writeFileSync('dist/server/host-entry.mjs', [
    "import server from './entry.mjs';",
    "import { canonicalRedirect } from './host.mjs';",
    '',
    '// Generated by scripts/postbuild.mjs. The framework handler serves matched',
    '// static assets before page middleware runs, so the canonical-host rule is',
    '// checked ahead of it for every request that reaches the Worker.',
    'export default {',
    '  async fetch(request, env, context) {',
    '    const destination = canonicalRedirect(request.url);',
    '    if (destination) return Response.redirect(destination, 301);',
    '    return server.fetch(request, env, context);',
    '  }',
    '}',
    ''
  ].join('\n'));

  const config = JSON.parse(readFileSync(serverConfigPath, 'utf8'));
  delete config.configPath;
  delete config.userConfigPath;
  delete config.dev;
  config.main = 'host-entry.mjs';
  // Every request reaches the Worker so the canonical-host rule runs before the
  // framework serves a matched static asset. Host-scoped pattern entries are
  // not part of the supported route syntax, so the boolean is the only form
  // that keeps the redirect working on static pages.
  config.assets.run_worker_first = true;
  writeFileSync(serverConfigPath, `${JSON.stringify(config)}\n`);
  console.log('Prepared the Worker deploy configuration with the host entry.');
} else {
  if (!existsSync(clientConfigPath)) throw new Error('No deploy configuration was generated by the build.');
  const config = JSON.parse(readFileSync(clientConfigPath, 'utf8'));
  delete config.configPath;
  delete config.userConfigPath;
  delete config.dev;
  writeFileSync(clientConfigPath, `${JSON.stringify(config)}\n`);
  console.log('Prepared the assets-only deploy configuration. Add a non-prerendered route to ship a Worker.');
}
